-- Calculate the moving average of order values for each customer over their order history.
SELECT Distinct
    c.customer_unique_id, o.order_purchase_timestamp as order_year, ot.order_value,
    AVG(ot.order_value) OVER(
        PARTITION BY c.customer_unique_id 
        ORDER BY o.order_purchase_timestamp
    ) AS moving_avg
FROM orders o
JOIN (SELECT order_id, SUM(price) AS order_value FROM order_items
group by order_id) ot
    ON o.order_id = ot.order_id
JOIN customers c 
    ON o.customer_id = c.customer_id
ORDER BY year(o.order_purchase_timestamp) asc, ot.order_value desc;


