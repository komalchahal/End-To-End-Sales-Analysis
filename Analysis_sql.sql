-- Calculate the year-over-year growth rate of total sales.
WITH yearlysales AS (
    SELECT YEAR(o.order_purchase_timestamp) AS year,
        SUM(oi.price) AS revenue
    FROM orders o
    JOIN order_items oi 
        ON o.order_id = oi.order_id
    GROUP BY year
    )
SELECT 
    year, revenue, LAG(revenue) OVER(ORDER BY year) AS lastyear_revenue,
    ROUND(((revenue - LAG(revenue) OVER(ORDER BY year)) / LAG(revenue) OVER(ORDER BY year)) * 100,2) 
    AS yoy_growth_rate FROM yearlysales;
    

-- Calculate the retention rate of customers, defined as the percentage of customers who make another purchase within 6 months of their first purchase.  
WITH FirstPurchase AS (
    SELECT c.customer_unique_id, 
	MIN(o.order_purchase_timestamp) AS first_order_date
    FROM customers c
    JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_unique_id ),
RetainedCustomers AS (
    SELECT DISTINCT f.customer_unique_id
    FROM FirstPurchase f
    JOIN customers c ON f.customer_unique_id = c.customer_unique_id
    JOIN orders o ON c.customer_id = o.customer_id
    WHERE o.order_purchase_timestamp > f.first_order_date 
      AND o.order_purchase_timestamp <= DATE_ADD(f.first_order_date, INTERVAL 6 MONTH))
SELECT 
    (SELECT COUNT(*) FROM FirstPurchase) AS total_customers,
    (SELECT COUNT(*) FROM RetainedCustomers) AS retained_customers,
    ROUND(
        (SELECT COUNT(*) FROM RetainedCustomers) * 100.0 / (SELECT COUNT(*) FROM FirstPurchase),2)
        AS retention_rate;

 
--  Identify the top 3 customers who spent the most money in each year.
Select order_year, customer_unique_id, total_spent
from (
SELECT YEAR(o.order_purchase_timestamp) AS order_year, c.customer_unique_id,
SUM(oi.price) AS total_spent,
DENSE_RANK() OVER (
PARTITION BY YEAR(o.order_purchase_timestamp) 
ORDER BY SUM(oi.price) DESC
) AS customer_rank
FROM orders o
JOIN customers c on o.customer_id = c.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
GROUP BY order_year, c.customer_unique_id
) AS ranked_customers
WHERE customer_rank <= 3
ORDER BY order_year DESC, total_spent desc;
 
 WITH YearlySpending AS (
    SELECT 
        YEAR(o.order_purchase_timestamp) AS order_year, 
        c.customer_unique_id, 
        SUM(oi.price)AS total_spent,
        DENSE_RANK() OVER (
            PARTITION BY YEAR(o.order_purchase_timestamp) 
            ORDER BY SUM(oi.price)desc
        ) AS customer_rank
    FROM orders o
    JOIN customers c ON o.customer_id = c.customer_id
    JOIN order_items oi ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered' 
    GROUP BY YEAR(o.order_purchase_timestamp), c.customer_unique_id
)
SELECT 
    order_year, customer_unique_id, total_spent
FROM YearlySpending
WHERE customer_rank <= 3
ORDER BY order_year DESC, total_spent desc;



